#!/usr/bin/env node
// Writes tools/iodd/iodd-units.json: every IO-Link unit code with its
// abbreviation and English name, read from IODD-StandardUnitDefinitions1.1.xml
// inside the official IODD 1.1.5 package (the same archive tools/iodd/schema.mjs
// pins). The archive is checked against the pinned sha256 before it is read.
//
//   node scripts/build-iodd-units.mjs [path/to/IO-Device-Description_Specification_10.012_V1.1.5_Oct2025.zip]
//
// Without a path the archive is downloaded from io-link.com. CI never runs this;
// the JSON is committed.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { unzipSync, strFromU8 } from "fflate";
import { SCHEMA_SOURCE } from "../tools/iodd/schema.mjs";
import { parseXml } from "../assets/js/iodd/vendor/model/xml.js";
import { elements, findAll, path, root } from "../assets/js/iodd/vendor/model/tree.js";

const target = fileURLToPath(new URL("../tools/iodd/iodd-units.json", import.meta.url));
// The same table as an ES module, so browsers, Workers and Node import it
// without JSON import attributes.
const moduleTarget = fileURLToPath(new URL("../tools/iodd/iodd-units.mjs", import.meta.url));
const source = process.argv[2];

async function archive() {
  if (source) return new Uint8Array(readFileSync(source));
  const response = await fetch(SCHEMA_SOURCE.url, { signal: AbortSignal.timeout(60000) });
  if (!response.ok) throw Error("download answered " + response.status);
  return new Uint8Array(await response.arrayBuffer());
}

const bytes = await archive();
const digest = createHash("sha256").update(bytes).digest("hex");
if (digest !== SCHEMA_SOURCE.sha256) throw Error("Archive digest " + digest + " does not match the pinned " + SCHEMA_SOURCE.sha256);
const files = unzipSync(bytes, { filter: (file) => /StandardDefinitions\/IODD-StandardUnitDefinitions1\.1\.xml$/.test(file.name) });
const name = Object.keys(files)[0];
if (!name) throw Error("IODD-StandardUnitDefinitions1.1.xml is not in the archive.");
const doc = parseXml(strFromU8(files[name]));
const top = root(doc);
const info = path(top, "DocumentInfo");
const texts = new Map(findAll(path(top, "ExternalTextCollection"), "Text").map((t) => [t.attrs.id, t.attrs.value]));
// Quantity kind, derived here from the English unit name (the package has no
// grouping). The converter uses it for categories and for the studio simulator.
const KINDS = [
  ["temperature", /^(kelvin|degree (celsius|fahrenheit|rankine))$/],
  ["pressure", /^(\w*pascal|bar|millibar|torr|atmosphere|pound-force per square inch|(kilo)?gram-force per square (centi)?meter)( absolute| gauge)?$|^(\w*meters?|inch(es)?|feet|foot) of (water|mercury)/],
  ["length", /^(kilo|centi|milli|micro|nano|pico)?meter$|^(foot|inch|yard|mile|nautical mile|ångström)$/],
  ["flow", /^(\w*liter|\w*gram|cubic \w+|(normal|standard) (cubic \w+|liter)|\w*gallon( \([^)]*\))?|barrel( \([^)]*\))?|metric ton|pound|short ton|long ton|acre foot) per (second|minute|hour|day)$/],
  ["velocity", /^(kilo|milli|centi)?(meter|foot|inch|yard|mile) per (second|minute|hour)$|^nautical mile per hour$/],
  ["time", /^(\w*second|minute|hour|day|year)$/],
  ["frequency", /^(\w*hertz|per minute|per second|revolutions? per (second|minute))$/],
  ["percent", /^(percent|per mille|volume percent|percent of weight|parts per \w+)$/],
  ["angle", /^(radian|degree|gon \(or grade\)|revolution)$/],
  ["volume", /^(\w*liter|cubic \w+|\w*gallon( \([^)]*\))?|barrel( \([^)]*\))?|pint.*|quart.*|bushel.*)$/],
  ["mass", /^(\w*gram|metric ton|ounce|pound|short ton|long ton)$/],
  ["force", /^(\w*newton|pound-force|kilogram-force|dyne)$/],
  ["electrical", /^\w*(ampere|volt|ohm|siemens|farad|watt|coulomb)$/],
];
// 1006/1007 are the angle minute and second, named like the time units.
const kindOf = (name, code) => (code === "1006" || code === "1007" ? "angle" : (KINDS.find((k) => k[1].test(name.toLowerCase())) || [])[0]);
const units = {};
elements(path(top, "UnitCollection"), "Unit").forEach((unit) => {
  const text = texts.get(unit.attrs.textId) || "";
  const entry = { abbr: unit.attrs.abbr, name: text };
  const kind = kindOf(text, unit.attrs.code);
  if (kind) entry.kind = kind;
  units[unit.attrs.code] = entry;
});
const out = {
  provenance: {
    source: "IODD-StandardUnitDefinitions1.1.xml in the IO-Link Community IODD 1.1.5 package",
    source_url: SCHEMA_SOURCE.url,
    archive_sha256: digest,
    archive_file: name,
    definitions_version: info && info.attrs.version,
    definitions_release_date: info && info.attrs.releaseDate,
    copyright: info && info.attrs.copyright,
    note: "Unit code, abbreviation and English name only (a fact table), regenerated by scripts/build-iodd-units.mjs. Unit definitions (c) IO-Link Community. kind is not in the package: it is derived from the English name by scripts/build-iodd-units.mjs.",
  },
  units,
};
const json = JSON.stringify(out, null, 0).replace(/},"/g, '},\n"') + "\n";
writeFileSync(target, json);
writeFileSync(moduleTarget, "// Generated by scripts/build-iodd-units.mjs from tools/iodd/iodd-units.json. Do not edit.\nexport default " + json.trimEnd() + ";\n");
console.log("wrote", Object.keys(units).length, "unit codes to", target);
